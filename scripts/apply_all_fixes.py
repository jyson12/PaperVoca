def main():
    data = json.loads(VOCAB_FILE.read_text(encoding="utf-8"))
    original_count = len(data["words"])

    removed = []
    kept_words = []
    pos_fixed = 0
    meaning_fixed = 0

    for w in data["words"]:
        word = w["word"]

        if word in NOISE_WORDS:
            removed.append(word)
            continue

        if word in FIXES:
            new_pos, new_meaning = FIXES[word]
            old_pos = w.get("pos", "")
            old_meaning = w.get("meaning_ko", "")

            if old_pos != new_pos:
                w["pos"] = new_pos
                w["pos_ko"] = POS_KO.get(new_pos, new_pos)
                pos_fixed += 1

            if new_meaning and old_meaning != new_meaning:
                w["meaning_ko"] = new_meaning
                meaning_fixed += 1

        kept_words.append(w)

    data["words"] = kept_words
    data["meta"]["word_count"] = len(kept_words)
    VOCAB_FILE.write_text(
        json.dumps(data, ensure_ascii=False, indent=2), encoding="utf-8"
    )

    print(f"원본 단어 수:  {original_count}개")
    print(f"노이즈 삭제:   {len(removed)}개  ({', '.join(removed)})")
    print(f"품사(POS) 수정: {pos_fixed}개")
    print(f"한국어 뜻 수정: {meaning_fixed}개")
    print(f"최종 단어 수:  {len(kept_words)}개")
    print("vocabulary.json 저장 완료")


if __name__ == "__main__":
    main()
